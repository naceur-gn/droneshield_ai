#!/usr/bin/env python3
"""Train the DroneShield decision tree and export it into the firmware.

Workflow:
    python make_dataset.py          # (or use your own dataset.csv from logs)
    python train_model.py           # trains + writes ../main/exported_model.c/.h
    idf.py build                    # firmware now uses the new tree

- Splits by capture session (GroupShuffleSplit), never random rows alone.
- Reports precision, recall, F1, confusion matrix, false-positive rate.
- Export target: main/exported_model.c + main/exported_model.h (compiled by ESP-IDF).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import GroupShuffleSplit
from sklearn.tree import DecisionTreeClassifier, export_text

HERE = Path(__file__).resolve().parent
DEFAULT_DATASET = HERE / "dataset.csv"
DEFAULT_OUT_DIR = HERE.parent / "droneshield_ai" / "main"   # firmware component folder

FEATURE_COLS = [
    "mqtt_msg_count",
    "avg_payload_len",
    "max_payload_len",
    "duplicate_count",
    "invalid_json_count",
    "unknown_topic_count",
    "invalid_command_count",
    "wifi_disconnect_count",
    "mqtt_reconnect_count",
    "uart_frame_error_count",
    "uart_bytes_per_second",
]


def export_c(model: DecisionTreeClassifier, out_dir: Path) -> None:
    tree = model.tree_
    nodes = []
    for i in range(tree.node_count):
        left = int(tree.children_left[i])
        right = int(tree.children_right[i])
        if left == right:  # leaf
            label = int(np.argmax(tree.value[i][0]))
            nodes.append((-1, 0.0, label, label))
        else:
            nodes.append((int(tree.feature[i]), float(tree.threshold[i]), left, right))

    def depth_of(idx: int, d: int = 0) -> int:
        fid, _, left, right = nodes[idx]
        if fid < 0:
            return d
        return max(depth_of(left, d + 1), depth_of(right, d + 1))

    max_depth = depth_of(0) if nodes else 1

    c_src = (
        "/* Generated by ai_model/train_model.py - do not edit by hand. */\n"
        '#include "exported_model.h"\n\n'
        "const dshl_ai_node_t DSHL_AI_TREE[] = {\n"
    )
    for fid, thr, left, right in nodes:
        c_src += f"    {{ {fid}, {thr:.6f}f, {left}, {right} }},\n"
    c_src += "};\n\n"
    c_src += f"const int DSHL_AI_TREE_LEN = {len(nodes)};\n"

    h_src = f"""/* Generated by ai_model/train_model.py - do not edit by hand. */
#pragma once

#include <stdint.h>

/* Node: feature >= 0 -> internal test (value <= threshold ? left : right)
 *       feature <  0 -> leaf; left encodes label (0=normal, 1=anomaly) */
typedef struct {{
    int8_t feature;
    float threshold;
    int32_t left;
    int32_t right;
}} dshl_ai_node_t;

#define DSHL_AI_TREE_MAX_DEPTH {max(max_depth, 1)}

extern const dshl_ai_node_t DSHL_AI_TREE[];
extern const int DSHL_AI_TREE_LEN;

/* Feature order must match feature_extractor.h / DSHL_FEATURE_NAMES */
#define DSHL_AI_FEATURE_COUNT {len(FEATURE_COLS)}
"""

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "exported_model.c").write_text(c_src, encoding="utf-8")
    (out_dir / "exported_model.h").write_text(h_src, encoding="utf-8")
    print(f"Exported tree: {len(nodes)} nodes, depth<={max_depth}")
    print(f"  -> {out_dir / 'exported_model.c'}")
    print(f"  -> {out_dir / 'exported_model.h'}")
    print("Now run: idf.py build")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    p.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR,
                   help="firmware folder to write exported_model.* (default: ../main)")
    p.add_argument("--max-depth", type=int, default=4)
    p.add_argument("--min-samples-leaf", type=int, default=5)
    args = p.parse_args()

    if not args.dataset.exists():
        print(f"Dataset not found: {args.dataset}", file=sys.stderr)
        print("Run: python make_dataset.py", file=sys.stderr)
        return 1

    df = pd.read_csv(args.dataset)
    missing = [c for c in FEATURE_COLS if c not in df.columns]
    if missing:
        print(f"Missing feature columns: {missing}", file=sys.stderr)
        return 1
    if "session_id" not in df.columns or "label" not in df.columns:
        print("dataset must have session_id and label columns", file=sys.stderr)
        return 1

    X = df[FEATURE_COLS]
    y = df["label"].astype(int)
    groups = df["session_id"]

    if groups.nunique() < 2:
        print("Need at least 2 capture sessions for a group split", file=sys.stderr)
        return 1

    splitter = GroupShuffleSplit(test_size=0.25, n_splits=1, random_state=42)
    train_idx, test_idx = next(splitter.split(X, y, groups=groups))

    model = DecisionTreeClassifier(
        max_depth=args.max_depth,
        min_samples_leaf=args.min_samples_leaf,
        class_weight="balanced",
        random_state=42,
    )
    model.fit(X.iloc[train_idx], y.iloc[train_idx])

    pred = model.predict(X.iloc[test_idx])
    y_test = y.iloc[test_idx]

    print("=== Classification report (held-out sessions) ===")
    print(classification_report(y_test, pred, digits=3, zero_division=0))
    cm = confusion_matrix(y_test, pred, labels=[0, 1])
    print("Confusion matrix [[TN FP][FN TP]]:")
    print(cm)

    tn, fp, fn, tp = (list(cm.ravel()) + [0, 0, 0, 0])[:4]
    fpr = fp / (fp + tn) if (fp + tn) else 0.0
    print(f"Precision: {precision_score(y_test, pred, zero_division=0):.3f}")
    print(f"Recall:    {recall_score(y_test, pred, zero_division=0):.3f}")
    print(f"F1:        {f1_score(y_test, pred, zero_division=0):.3f}")
    print(f"Accuracy:  {(pred == y_test.to_numpy()).mean():.3f}")
    print(f"False positive rate: {fpr:.3f}")
    print(f"Train sessions: {sorted(set(groups.iloc[train_idx]))}")
    print(f"Test sessions:  {sorted(set(groups.iloc[test_idx]))}")
    print("\n=== Tree rules ===")
    print(export_text(model, feature_names=FEATURE_COLS))

    export_c(model, args.out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
